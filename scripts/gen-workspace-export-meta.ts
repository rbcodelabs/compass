/**
 * Generates lib/workspace-export/schema-meta.generated.ts from prisma/schema.prisma.
 *
 * The Prisma runtime datamodel does not carry nullability, and the importer
 * needs to know which String columns may be set to NULL when they point at something that is
 * not part of the export. A test fails when this file is stale: run
 *   node scripts/gen-workspace-export-meta.ts
 */
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import path from "node:path"

export function parseOptionalStringFields(schema: string): Record<string, string[]> {
  const out: Record<string, string[]> = {}
  let current: string | null = null
  for (const line of schema.split("\n")) {
    const open = /^model\s+(\w+)\s*\{/.exec(line)
    if (open) {
      current = open[1]
      continue
    }
    if (current && /^\}/.test(line)) {
      current = null
      continue
    }
    if (!current) continue
    const field = /^\s+(\w+)\s+String\?(\s|$)/.exec(line)
    if (field) (out[current] ??= []).push(field[1])
  }
  return out
}

const SCALARS = new Set(["String", "Int", "Float", "Boolean", "DateTime", "Json", "BigInt", "Decimal", "Bytes"])

/** Every optional scalar or enum column per model (relation fields excluded). */
export function parseOptionalFields(schema: string): Record<string, string[]> {
  const enums = new Set<string>()
  for (const m of schema.matchAll(/^enum\s+(\w+)\s*\{/gm)) enums.add(m[1])
  const out: Record<string, string[]> = {}
  let current: string | null = null
  for (const line of schema.split("\n")) {
    const open = /^model\s+(\w+)\s*\{/.exec(line)
    if (open) {
      current = open[1]
      continue
    }
    if (current && /^\}/.test(line)) {
      current = null
      continue
    }
    if (!current) continue
    const field = /^\s+(\w+)\s+(\w+)\?(\s|$)/.exec(line)
    if (field && (SCALARS.has(field[2]) || enums.has(field[2]))) (out[current] ??= []).push(field[1])
  }
  return out
}

function renderMap(name: string, meta: Record<string, string[]>): string {
  const body = Object.keys(meta)
    .sort()
    .map((m) => `  ${m}: ${JSON.stringify([...meta[m]].sort())},`)
    .join("\n")
  return `export const ${name}: Readonly<Record<string, readonly string[]>> = {\n${body}\n}\n`
}

export function render(schema: string): string {
  return `// GENERATED by scripts/gen-workspace-export-meta.ts from prisma/schema.prisma. Do not edit.\n${renderMap("OPTIONAL_STRING_FIELDS", parseOptionalStringFields(schema))}${renderMap("OPTIONAL_FIELDS", parseOptionalFields(schema))}`
}

const here = path.dirname(fileURLToPath(import.meta.url))
export const SCHEMA_PATH = path.join(here, "../prisma/schema.prisma")
export const OUTPUT_PATH = path.join(here, "../lib/workspace-export/schema-meta.generated.ts")

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT_PATH, render(readFileSync(SCHEMA_PATH, "utf8")))
  console.log("wrote", OUTPUT_PATH)
}
