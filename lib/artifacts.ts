/** PNG magic bytes. Cheap guard that we are storing what we claim to. */
const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])

export function validateThumbnailPng(bytes: Uint8Array): { ok: true } | { ok: false; error: string } {
  if (bytes.byteLength === 0) return { ok: false, error: "Screenshot is empty" }
  if (bytes.byteLength > MAX_ARTIFACT_THUMBNAIL_BYTES) {
    return { ok: false, error: `Screenshot exceeds the ${MAX_ARTIFACT_THUMBNAIL_BYTES} byte limit` }
  }
  if (!Buffer.from(bytes.subarray(0, PNG_SIGNATURE.length)).equals(PNG_SIGNATURE)) {
    return { ok: false, error: "Screenshot is not a PNG" }
  }
  return { ok: true }
}

/**
 * Attach a captured screenshot to one Artifact revision.
 *
 * Revisions are insert-only for *content*, but a thumbnail is derived data about
 * a revision, not content of it — so this updates the existing row rather than
 * minting a revision. Re-capturing the same revision is therefore idempotent
 * from the caller's point of view and does not inflate the revision history.
 *
 * ORDERING — write the new blob, repoint the row, then enqueue the OLD blob for
 * deletion. Deleting first would leave a window where the row points at nothing;
 * this way the failure mode is an orphaned blob, which the cleanup outbox exists
 * to sweep, rather than a broken image.
 */
export async function setArtifactRevisionThumbnail(
  input: {
    artifactId: string
    workspaceId: string
    /** Defaults to the artifact's current revision. */
    revisionId?: string
    png: Uint8Array
    width: number
    height: number
    /**
     * The URL actually rendered, after redirects. Null for an HTML_UPLOAD
     * capture, which renders the stored bytes directly and has no URL at all.
     */
    sourceUrl: string | null
    capturedAt?: Date
  },
  storage: ArtifactStorage
) {
  const validation = validateThumbnailPng(input.png)
  if (!validation.ok) throw new Error(validation.error)

  const prisma = getPrisma()
  const artifact = await prisma.artifact.findFirst({
    where: { id: input.artifactId, workspaceId: input.workspaceId },
    select: { id: true, currentRevisionId: true },
  })
  if (!artifact) throw new Error("Artifact not found")

  const targetRevisionId = input.revisionId ?? artifact.currentRevisionId
  if (!targetRevisionId) throw new Error("Artifact has no revision to attach a screenshot to")

  const revision = await prisma.artifactRevision.findFirst({
    where: { id: targetRevisionId, artifactId: artifact.id },
    select: { id: true, thumbnailPathname: true },
  })
  if (!revision) throw new Error("Artifact revision not found")

  const previousPathname = revision.thumbnailPathname
  // A fresh object per capture: overwriting in place would race against anything
  // currently serving the old bytes, and costs nothing to avoid.
  const pathname = `artifacts/${input.workspaceId}/${artifact.id}/thumbnails/${revision.id}-${randomUUID()}.png`
  const stored = await storage.put(pathname, input.png)

  try {
    const updated = await prisma.artifactRevision.update({
      where: { id: revision.id },
      data: {
        thumbnailPathname: stored.pathname,
        thumbnailMimeType: "image/png",
        thumbnailByteSize: input.png.byteLength,
        thumbnailWidth: input.width,
        thumbnailHeight: input.height,
        thumbnailCapturedAt: input.capturedAt ?? new Date(),
        thumbnailSourceUrl: input.sourceUrl,
      },
      select: {
        id: true,
        revisionNumber: true,
        thumbnailByteSize: true,
        thumbnailWidth: true,
        thumbnailHeight: true,
        thumbnailCapturedAt: true,
        thumbnailSourceUrl: true,
      },
    })
    if (previousPathname && previousPathname !== stored.pathname) {
      // Best-effort: a failed enqueue costs storage, not correctness, and must
      // not fail a capture that already succeeded.
      await enqueueBlobCleanup(prisma, [previousPathname], "THUMBNAIL_REPLACED").catch(
        () => undefined
      )
    }
    return updated
  } catch (error) {
    await compensateBlob(prisma, storage, stored.pathname, error)
    throw error
  }
}

// ── Artifact links ──────────────────────────────────────────────────────────
// entity_links is the only store (ADR "One generic entity_links table"; migration 096 moved the old artifact_links rows). This module is
// the dedicated writer of ARTIFACT_ATTACHED_TO_SOLUTION and ARTIFACT_SUPPORTS_DECISION: every write runs in ONE retried link transaction
// through lib/links/service.ts. A lost race on the unique pair aborts the transaction, so runTypedLinkTransaction re-runs it and the
// repeat read returns the winner.
// These are never called inside an MCP tool receipt transaction (hasToolTransaction): that wrapper exists only for the PM-interview update
// tools, and link_artifact_* are not among them (they are denied in interview contexts). Were one ever wrapped, withWorkspaceUpdates would
// reuse the outer transaction and a pair race could not be retried here; the caller's own retry would then see the winner.

const entityLinkService = () => import("@/lib/links/service")
const entityLinkReaders = () => import("@/lib/links/readers")
const ARTIFACT_SOLUTION = "ARTIFACT_ATTACHED_TO_SOLUTION"
const ARTIFACT_DECISION = "ARTIFACT_SUPPORTS_DECISION"

/** The shape the link tools and actions have always returned: the link row plus whether this call created it. */
const linkResult = (link: { id: string; workspaceId: string; fromId: string; toId: string; toType: string; source: string; createdById: string | null; createdAt: Date }, created: boolean) => ({
  id: link.id, workspaceId: link.workspaceId, artifactId: link.fromId, linkedType: link.toType, linkedId: link.toId,
  source: link.source, createdById: link.createdById, createdAt: link.createdAt, created,
})

export async function linkArtifactToSolution(input: {
  artifactId: string; solutionId: string; workspaceId: string; createdById?: string | null; source?: Source
}) {
  return runTypedLinkTransaction(getPrisma(), async (tx) => {
    const artifact = await tx.artifact.findFirst({ where: { id: input.artifactId, workspaceId: input.workspaceId }, select: { id: true, workspaceId: true } })
    const solution = await tx.solution.findFirst({ where: { id: input.solutionId, workspaceId: input.workspaceId }, select: { id: true } })
    if (!artifact || !solution) throw new Error("Artifact and Solution must exist in the same workspace")
    const { linkEntities } = await entityLinkService()
    const result = await linkEntities(tx, {
      linkType: ARTIFACT_SOLUTION, fromId: artifact.id, toId: solution.id, expectedWorkspaceId: input.workspaceId,
      ctx: { source: input.source ?? "UI", createdById: input.createdById ?? null }, viaDedicatedWriter: true,
    })
    return linkResult(result.link, result.created)
  })
}

export async function unlinkArtifactFromSolution(input: { artifactId: string; solutionId: string; workspaceId: string }) {
  return runTypedLinkTransaction(getPrisma(), async (tx) => {
    const artifact = await tx.artifact.findFirst({ where: { id: input.artifactId, workspaceId: input.workspaceId }, select: { id: true } })
    if (!artifact) throw new Error("Artifact not found")
    const { unlinkEntities } = await entityLinkService()
    const result = await unlinkEntities(tx, { linkType: ARTIFACT_SOLUTION, fromId: artifact.id, toId: input.solutionId, expectedWorkspaceId: input.workspaceId, viaDedicatedWriter: true })
    return { removed: result.removed > 0 }
  })
}

type DecisionArtifactInput = { artifactId: string; requestId: string; workspaceId: string }

async function assertDecisionArtifactTargets(tx: AppTransactionClient, input: DecisionArtifactInput) {
  const artifact = await tx.artifact.findFirst({ where: { id: input.artifactId, workspaceId: input.workspaceId }, select: { id: true, status: true } })
  const request = await tx.reviewRequest.findFirst({ where: { id: input.requestId, workspaceId: input.workspaceId, gateType: "TRACKED_DECISION" }, select: { id: true } })
  if (!artifact || !request) throw new Error("Artifact and Decision must exist in the same workspace")
  return artifact
}

export async function linkArtifactToDecision(input: DecisionArtifactInput & { createdById?: string | null; source?: Source }) {
  return runTypedLinkTransaction(getPrisma(), async (tx) => {
    const artifact = await assertDecisionArtifactTargets(tx, input)
    const { linkEntities, findLink } = await entityLinkService()
    // A replay of an existing link is fine for an archived Artifact; only a NEW link is refused.
    const existing = await findLink(tx, { linkType: ARTIFACT_DECISION, fromId: input.artifactId, toId: input.requestId, workspaceId: input.workspaceId })
    if (!existing && artifact.status === "ARCHIVED") throw new Error("Archived Artifacts cannot be linked to a Decision")
    const result = await linkEntities(tx, {
      linkType: ARTIFACT_DECISION, fromId: input.artifactId, toId: input.requestId, expectedWorkspaceId: input.workspaceId,
      ctx: { source: input.source ?? "UI", createdById: input.createdById ?? null }, viaDedicatedWriter: true,
    })
    return linkResult(result.link, result.created)
  })
}

export async function unlinkArtifactFromDecision(input: DecisionArtifactInput) {
  return runTypedLinkTransaction(getPrisma(), async (tx) => {
    await assertDecisionArtifactTargets(tx, input)
    const { unlinkEntities } = await entityLinkService()
    const result = await unlinkEntities(tx, { linkType: ARTIFACT_DECISION, fromId: input.artifactId, toId: input.requestId, expectedWorkspaceId: input.workspaceId, viaDedicatedWriter: true })
    return { removed: result.removed > 0 }
  })
}

