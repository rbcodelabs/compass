export type ArtifactThumbnailDto = { src: string; width: number; height: number; capturedAt: string }

/**
 * The browser-facing view of a revision's screenshot: a same-origin URL to the
 * authenticated thumbnail route, plus the dimensions needed to reserve layout.
 *
 * The storage key is read only to decide whether a thumbnail exists — it is never
 * copied into the result. Blob pathnames are private (they are guessable from
 * ids), so the client gets a route that re-checks access on every request.
 *
 * `v` is the capture time, so a re-capture changes the URL. The route answers
 * `no-store`, so this is not about cache invalidation — it makes React swap the
 * <img> rather than keep showing the old decoded bitmap.
 */
export function toThumbnailDto(
  artifactId: string,
  revision: { id?: string; thumbnailPathname?: string | null; thumbnailWidth?: number | null; thumbnailHeight?: number | null; thumbnailCapturedAt?: Date | null }
): ArtifactThumbnailDto | null {
  if (!revision.id || !revision.thumbnailPathname || !revision.thumbnailWidth || !revision.thumbnailHeight || !revision.thumbnailCapturedAt) return null
  const capturedAt = revision.thumbnailCapturedAt
  return {
    src: `/api/artifacts/${artifactId}/revisions/${revision.id}/thumbnail?v=${capturedAt.getTime()}`,
    width: revision.thumbnailWidth,
    height: revision.thumbnailHeight,
    capturedAt: capturedAt.toISOString(),
  }
}

export async function deleteArtifact(input: { artifactId: string; workspaceId: string }, storage: ArtifactStorage) {
  const prisma = getPrisma()
  const artifact = await prisma.artifact.findFirst({ where: { id: input.artifactId, workspaceId: input.workspaceId }, include: { revisions: { select: { blobPathname: true, thumbnailPathname: true } } } })
  if (!artifact) throw new Error("Artifact not found")
  // Thumbnails are separate blobs from content, so both must be queued or the
  // thumbnail bytes outlive the artifact forever (nothing else references them).
  const pathnames = artifact.revisions.flatMap((revision) => [revision.blobPathname, revision.thumbnailPathname].filter((p): p is string => Boolean(p)))
  await enqueueBlobCleanup(prisma, pathnames, "ARTIFACT_DELETE")
  // Links go FIRST: a failed sweep leaves the Artifact untouched (the delete is simply retried), while a failed LATER delete leaves an
  // Artifact with no links, which is a valid state.
  await (await entityLinkService()).deleteLinksForEntity(prisma, "ARTIFACT", [artifact.id])
  // The frozen artifact_links rows of this Artifact would Restrict its delete (relationMode = "prisma").
  await deleteFrozenArtifactLinks(prisma, { artifactId: artifact.id })
  await prisma.artifact.update({ where: { id: artifact.id }, data: { currentRevisionId: null, updatedAt: new Date() } })
  await prisma.artifactRevision.deleteMany({ where: { artifactId: artifact.id } })
  await prisma.artifact.delete({ where: { id: artifact.id } })
  await retryArtifactBlobCleanup(prisma, storage)
}

type PrismaClient = ReturnType<typeof getPrisma>
type WorkspaceArtifactCleanupClient = {
  artifact: Pick<PrismaClient["artifact"], "findMany" | "updateMany" | "deleteMany">
  artifactRevision: Pick<PrismaClient["artifactRevision"], "findMany" | "findFirst" | "deleteMany">
  artifactLink: Pick<PrismaClient["artifactLink"], "deleteMany">
  artifactBlobCleanup: Pick<PrismaClient["artifactBlobCleanup"], "upsert" | "findMany" | "update" | "delete">
}

/** Removes every Artifact child row before its workspace in the explicit order
 * required by DSQL, then best-effort removes the now-unreferenced private blobs. */
export async function deleteWorkspaceArtifacts(
  prisma: WorkspaceArtifactCleanupClient,
  workspaceId: string,
  storage: ArtifactStorage,
  retryCleanup = true
) {
  const artifacts = await prisma.artifact.findMany({ where: { workspaceId }, select: { id: true } })
  const artifactIds = artifacts.map((artifact) => artifact.id)
  const revisions = artifactIds.length === 0 ? [] : await prisma.artifactRevision.findMany({
    where: { artifactId: { in: artifactIds } }, select: { blobPathname: true, thumbnailPathname: true },
  })
  // Content AND thumbnail blobs — see the note in deleteArtifact.
  const pathnames = revisions.flatMap((revision) => [revision.blobPathname, revision.thumbnailPathname].filter((p): p is string => Boolean(p)))
  await enqueueBlobCleanup(prisma, pathnames, "WORKSPACE_DELETE")
  // entity_links for the workspace are swept by the cascade; the frozen artifact_links rows would Restrict the Artifact delete.
  await deleteFrozenWorkspaceArtifactLinks(prisma, { workspaceId })
  await prisma.artifact.updateMany({ where: { workspaceId }, data: { currentRevisionId: null, updatedAt: new Date() } })
  if (artifactIds.length > 0) {
    await prisma.artifactRevision.deleteMany({ where: { artifactId: { in: artifactIds } } })
  }
  await prisma.artifact.deleteMany({ where: { workspaceId } })
  if (retryCleanup) await retryArtifactBlobCleanup(prisma, storage)
}
